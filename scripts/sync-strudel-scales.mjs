#!/usr/bin/env bun
/**
 * Vendors the scale names @strudel/repl actually accepts into
 * tests/fixtures/strudel-scale-names.json.
 *
 * Why not just ask the `tonal` npm package? Because the bundled copy can drift
 * from ours: @strudel/repl@1.3.0 ships tonal's older table, which spells the
 * scale "neopolitan major" where tonal 6.4.3 spells it "neapolitan major".
 * A guide that names a scale only one of the two knows still produces silence
 * (@strudel/tonal throws `Invalid scale name` and the layer emits no notes),
 * so tests/guide-scales.test.ts checks guide names against the intersection.
 *
 * The scale dictionary lives in the REPL's big dist chunk as a literal array of
 * ["<intervals>", "<name>", ...aliases] tuples; this scrapes exactly that.
 *
 * Usage: bun scripts/sync-strudel-scales.mjs
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURES = join(ROOT, "tests", "fixtures");

export const STRUDEL_REPL_VERSION = "1.3.0";
const PKG = `https://unpkg.com/@strudel/repl@${STRUDEL_REPL_VERSION}`;

/** ["1P 2M 3M 4P 5P 6M 7M", "major", "ionian"] */
const SCALE_TUPLE = /\[\s*"((?:\d{1,2}[PMmAd]\s*)+)"((?:\s*,\s*"[^"\n]+")+)\s*\]/g;

async function largestDistChunk() {
  const meta = await (await fetch(`${PKG}/?meta`)).json();
  const files = (meta.files ?? []).filter((f) => f.path.endsWith(".js") && f.path.startsWith("/dist/"));
  if (files.length === 0) throw new Error("no dist chunks listed for " + PKG);
  files.sort((a, b) => b.size - a.size);
  return files[0].path;
}

async function main() {
  const chunk = await largestDistChunk();
  console.error(`reading ${PKG}${chunk}`);
  const src = await (await fetch(`${PKG}${chunk}`)).text();

  // Narrow to the scale dictionary literal: it is one array assignment whose
  // last entry is the 12-note chromatic scale. (The chord dictionary has the
  // same tuple shape, so scraping the whole chunk would mix chords in.)
  const endMarker = src.indexOf('"1P 2m 2M 3m 3M 4P 5d 5P 6m 6M 7m 7M",');
  if (endMarker < 0) throw new Error("chromatic scale entry not found — the shape changed");
  const head = src.slice(0, endMarker);
  const starts = [...head.matchAll(/[A-Za-z_$][\w$]*\s*=\s*\[/g)];
  const start = starts[starts.length - 1].index;
  const end = src.indexOf("]", src.indexOf("]", endMarker) + 1);
  const table = src.slice(start, end);

  const names = new Set();
  for (const m of table.matchAll(SCALE_TUPLE)) {
    for (const n of m[2].matchAll(/"([^"\n]+)"/g)) names.add(n[1]);
  }
  if (names.size < 80) throw new Error(`only scraped ${names.size} scale names — the shape changed`);

  const fixture = {
    _comment:
      "Generated by scripts/sync-strudel-scales.mjs — do not edit by hand. " +
      `Scale names (incl. aliases) in @strudel/repl@${STRUDEL_REPL_VERSION}. ` +
      "Strudel maps '.scale(\"C4:whole:tone\")' to Scale.get('C4 whole tone'), " +
      "so these are space-separated.",
    strudelReplVersion: STRUDEL_REPL_VERSION,
    chunk,
    names: [...names].sort(),
  };

  const out = join(FIXTURES, "strudel-scale-names.json");
  await writeFile(out, `${JSON.stringify(fixture, null, 2)}\n`);
  console.error(`wrote ${out}\n  ${fixture.names.length} scale names + aliases`);
}

await main();
