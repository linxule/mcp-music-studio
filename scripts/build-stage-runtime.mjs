// Bundles src/shared/stage-runtime.ts (via stage-runtime-global.ts) into an
// IIFE string for the standalone share page — src/generated/stage-runtime-js.ts.
// Runs at the start of `bun run build`. The file records a hash of its inputs;
// tests/share-page-stage.test.ts fails when the bundle is stale.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const STAGE_INPUTS = [
  "src/shared/stage-runtime.ts",
  "src/shared/stage-runtime-global.ts",
  "src/shared/hap-number.ts",
  "src/shared/tts.ts",
  "src/shared/sample-url-fix.ts",
  "src/shared/remember-store.ts",
  "src/shared/sing.ts",
  "src/shared/sing-dsp.ts",
];

const hash = createHash("sha256");
for (const file of STAGE_INPUTS) hash.update(readFileSync(join(root, file)));
const digest = hash.digest("hex").slice(0, 16);

const result = await Bun.build({
  entrypoints: [join(root, "src/shared/stage-runtime-global.ts")],
  format: "iife",
  target: "browser",
  minify: false,
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
let js = await result.outputs[0].text();
// Inlined into a <script>: never let the text close it.
js = js.replace(/<\/(script)/gi, "<\\/$1");

writeFileSync(
  join(root, "src/generated/stage-runtime-js.ts"),
  "// AUTO-GENERATED by scripts/build-stage-runtime.mjs — do not edit by hand.\n" +
    `export const STAGE_RUNTIME_INPUTS_HASH = ${JSON.stringify(digest)};\n` +
    `export const STAGE_RUNTIME_JS = ${JSON.stringify(js)};\n`,
);
console.error(`[build-stage-runtime] src/generated/stage-runtime-js.ts (${js.length} chars, inputs ${digest})`);
